#!/usr/bin/env bash
# Build the Rust Lambda, deploy the SAM stack, generate web/js/config.js and
# publish the PWA. Run from Linux, macOS, WSL or CI (see docs/DEPLOY.md).
#
#   COGNITO_DOMAIN_PREFIX=myptapp-dev ./scripts/deploy.sh
#
set -euo pipefail
cd "$(dirname "$0")/.."

STAGE="${STAGE:-dev}"
STACK="${STACK:-ptapp-$STAGE}"
REGION="${AWS_REGION:-${AWS_DEFAULT_REGION:-us-east-1}}"
: "${COGNITO_DOMAIN_PREFIX:?set COGNITO_DOMAIN_PREFIX to a globally unique name, e.g. myptapp-dev}"

echo "==> building Lambda (arm64)"
cargo lambda build --release --arm64 --bin api

# With DEPLOY_ROLE_STACK=1 (set by CI), deploy through the roles and bucket
# from scripts/ci-deploy-role.yaml: CloudFormation runs as its execution
# role and every IAM role in the stack carries the permissions boundary.
# Otherwise deploy with your own credentials and SAM's managed bucket.
DEPLOY_ARGS=(--resolve-s3)
PARAMS=("Stage=$STAGE" "CognitoDomainPrefix=$COGNITO_DOMAIN_PREFIX")
if [ "${DEPLOY_ROLE_STACK:-}" = 1 ]; then
  ACCOUNT="$(aws sts get-caller-identity --query Account --output text)"
  DEPLOY_ARGS=(--role-arn "arn:aws:iam::$ACCOUNT:role/cfn-exec-ptapp-$STAGE" --s3-bucket "ptapp-$STAGE-sam-artifacts-$ACCOUNT")
  PARAMS+=("PermissionsBoundary=arn:aws:iam::$ACCOUNT:policy/ptapp-$STAGE-boundary")
fi

echo "==> deploying stack $STACK to $REGION"
sam deploy \
  --template-file template.yaml \
  --stack-name "$STACK" \
  --region "$REGION" \
  --capabilities CAPABILITY_IAM \
  "${DEPLOY_ARGS[@]}" \
  --no-confirm-changeset \
  --no-fail-on-empty-changeset \
  --parameter-overrides "${PARAMS[@]}"

out() {
  aws cloudformation describe-stacks --region "$REGION" --stack-name "$STACK" \
    --query "Stacks[0].Outputs[?OutputKey=='$1'].OutputValue" --output text
}
API_URL="$(out ApiUrl)"
APP_URL="$(out AppUrl)"
COGNITO_DOMAIN="$(out CognitoDomain)"
CLIENT_ID="$(out UserPoolClientId)"
WEB_BUCKET="$(out WebBucketName)"
DIST_ID="$(out DistributionId)"

# Publish from a copy so the generated config and the stamped service-worker
# version never touch the tracked files (web/js/config.js stays the dev config).
SITE="$(mktemp -d)"
trap 'rm -rf "$SITE"' EXIT
cp -R web/. "$SITE/"

echo "==> generating js/config.js"
cat > "$SITE/js/config.js" <<EOF
// Generated by scripts/deploy.sh for stack $STACK. Do not edit by hand.
export default {
  apiUrl: "$API_URL",
  cognitoDomain: "$COGNITO_DOMAIN",
  clientId: "$CLIENT_ID",
  devUser: false,
};
EOF

echo "==> publishing web app to s3://$WEB_BUCKET"
VERSION="$(date -u +%Y%m%d%H%M%S)"
sed -i.bak "s/const VERSION = '[^']*'/const VERSION = '$VERSION'/" "$SITE/sw.js" && rm -f "$SITE/sw.js.bak"
aws s3 sync "$SITE/" "s3://$WEB_BUCKET/" --region "$REGION" --delete \
  --exclude "index.html" --exclude "sw.js" --exclude "js/config.js" \
  --cache-control "public,max-age=300"
for f in index.html sw.js js/config.js; do
  aws s3 cp "$SITE/$f" "s3://$WEB_BUCKET/$f" --region "$REGION" --cache-control "no-cache"
done
aws cloudfront create-invalidation --distribution-id "$DIST_ID" --paths "/*" >/dev/null

echo
echo "App:  $APP_URL"
echo "API:  $API_URL"
