#!/usr/bin/env bash
# Build the Rust Lambda, deploy the SAM stack, generate web/js/config.js and
# publish the PWA. Run from Linux, macOS, WSL or Git Bash (see docs/DEPLOY.md).
#
#   COGNITO_DOMAIN_PREFIX=myptapp-dev ADMIN_EMAILS=you@example.com \
#     INVITE_FROM=invites@example.com ./scripts/deploy.sh
#
# ADMIN_EMAILS lists who may set up an admin account (admins onboard
# coaches). Pass it on every deploy: leaving it out clears the list, though
# admin accounts that already exist keep working.
# INVITE_FROM is the sender for invitation emails; its domain must have the
# DKIM records from the DkimRecord outputs in its DNS. Leaving it out turns
# emailing off (invitations are then shared by link only).
set -euo pipefail
cd "$(dirname "$0")/.."

STAGE="${STAGE:-dev}"
STACK="${STACK:-ptapp-$STAGE}"
REGION="${AWS_REGION:-${AWS_DEFAULT_REGION:-us-east-1}}"
: "${COGNITO_DOMAIN_PREFIX:?set COGNITO_DOMAIN_PREFIX to a globally unique name, e.g. myptapp-dev}"
ADMIN_EMAILS="${ADMIN_EMAILS:-}"
INVITE_FROM="${INVITE_FROM:-}"
# APP_DOMAIN (e.g. gymtxcoach.com) serves the app at its own domain, with
# APP_CERT_ARN an ACM certificate in us-east-1 for it and www (DEPLOY.md).
APP_DOMAIN="${APP_DOMAIN:-}"
APP_CERT_ARN="${APP_CERT_ARN:-}"
# ALARM_EMAIL gets an email when the API's errors spike (confirm AWS's first email).
ALARM_EMAIL="${ALARM_EMAIL:-}"
# "false" if INVITE_FROM's domain is already an SES identity made outside this stack.
CREATE_SENDER_IDENTITY="${CREATE_SENDER_IDENTITY:-true}"

echo "==> building Lambdas (arm64): the API and the hourly sweep"
cargo lambda build --release --arm64 --bin api
cargo lambda build --release --arm64 --bin sweep

# Web Push key (push.rs): made once per stage, kept in SSM, never printed.
# MSYS_NO_PATHCONV stops Git Bash turning the /ptapp/... name into a Windows path.
VAPID_PARAM="/ptapp/$STAGE/vapid-private-key"
if ! MSYS_NO_PATHCONV=1 aws ssm get-parameter --region "$REGION" --name "$VAPID_PARAM" >/dev/null 2>&1; then
  echo "==> creating the Web Push key $VAPID_PARAM"
  MSYS_NO_PATHCONV=1 aws ssm put-parameter --region "$REGION" --name "$VAPID_PARAM" --type SecureString \
    --value "$(cargo run -q --release -p api --bin vapid_keys)" >/dev/null
fi

echo "==> deploying stack $STACK to $REGION"
sam deploy \
  --template-file template.yaml \
  --stack-name "$STACK" \
  --region "$REGION" \
  --capabilities CAPABILITY_IAM \
  --resolve-s3 \
  --no-confirm-changeset \
  --no-fail-on-empty-changeset \
  --parameter-overrides "Stage=$STAGE" "CognitoDomainPrefix=$COGNITO_DOMAIN_PREFIX" "AdminEmails=$ADMIN_EMAILS" "InviteFromAddress=$INVITE_FROM" "CreateSenderIdentity=$CREATE_SENDER_IDENTITY" \
    "AppDomain=$APP_DOMAIN" "AppCertificateArn=$APP_CERT_ARN" "AlarmEmail=$ALARM_EMAIL"

out() {
  aws cloudformation describe-stacks --region "$REGION" --stack-name "$STACK" \
    --query "Stacks[0].Outputs[?OutputKey=='$1'].OutputValue" --output text
}
API_URL="$(out ApiUrl)"
APP_URL="$(out AppUrl)"
COGNITO_DOMAIN="$(out CognitoDomain)"
CLIENT_ID="$(out UserPoolClientId)"
WEB_BUCKET="$(out WebBucketName)"
DIST_ID="$(out DistributionId)"
EVENTS_HTTP="$(out EventsHttpDomain)"
EVENTS_REALTIME="$(out EventsRealtimeDomain)"

# Publish from a copy so the generated config and the stamped service-worker
# version never touch the tracked files (web/js/config.js stays the dev config).
SITE="$(mktemp -d)"
trap 'rm -rf "$SITE"' EXIT
cp -R web/. "$SITE/"

echo "==> generating js/config.js"
cat > "$SITE/js/config.js" <<EOF
// Generated by scripts/deploy.sh for stack $STACK. Do not edit by hand.
export default {
  apiUrl: "$API_URL",
  cognitoDomain: "$COGNITO_DOMAIN",
  region: "$REGION",
  clientId: "$CLIENT_ID",
  eventsHttp: "$EVENTS_HTTP",
  eventsRealtime: "$EVENTS_REALTIME",
  devUser: false,
};
EOF

echo "==> publishing web app to s3://$WEB_BUCKET"
VERSION="$(date -u +%Y%m%d%H%M%S)"
sed -i.bak "s/const VERSION = '[^']*'/const VERSION = '$VERSION'/" "$SITE/sw.js" && rm -f "$SITE/sw.js.bak"
aws s3 sync "$SITE/" "s3://$WEB_BUCKET/" --region "$REGION" --delete \
  --exclude "index.html" --exclude "sw.js" --exclude "js/config.js" \
  --cache-control "public,max-age=300"
for f in index.html sw.js js/config.js; do
  aws s3 cp "$SITE/$f" "s3://$WEB_BUCKET/$f" --region "$REGION" --cache-control "no-cache"
done
aws cloudfront create-invalidation --distribution-id "$DIST_ID" --paths "/*" >/dev/null

# Smoke check: the browser's CORS preflight must succeed, or every signed-in
# call fails in the browser (shown as "Can't reach the server").
PREFLIGHT="$(curl -s -o /dev/null -w '%{http_code}' -X OPTIONS "$API_URL/me" \
  -H "Origin: $APP_URL" -H 'Access-Control-Request-Method: GET' \
  -H 'Access-Control-Request-Headers: authorization,content-type')"
case "$PREFLIGHT" in
  2??) echo "==> smoke check: CORS preflight OK ($PREFLIGHT)" ;;
  *) echo "!! smoke check FAILED: CORS preflight to $API_URL/me returned $PREFLIGHT; signed-in users can't reach the API" >&2; exit 1 ;;
esac

echo
echo "App:  $APP_URL"
echo "API:  $API_URL"
